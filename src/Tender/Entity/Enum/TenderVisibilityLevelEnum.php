<?php

declare(strict_types=1);

namespace App\Tender\Entity\Enum;

/**
 * Круг видимости тендера в текущем статусе (FR-1.5.14).
 *
 * Видимость закупки не постоянна: она открывается на время торговых стадий
 * и снова сужается, когда закупка уходит во внутреннюю работу заказчика или
 * к конкретному исполнителю. Уровень задаёт TenderStatusEnum::visibilityLevel().
 */
enum TenderVisibilityLevelEnum
{
    /**
     * Только сотрудники компании-создателя: черновик и отозванная публикация.
     * Объявленной процедуры ещё нет — наружу показывать нечего.
     */
    case OWNER_ONLY;

    /**
     * Активная часть процедуры (от публикации до исполнения договора): тендер
     * виден всем, а закрытый (access_type = contract_holders) — заказчику и
     * компаниям с действующим многоразовым договором с ним. Видно при этом
     * только публичное: состав карточки ограничивает App\Tender\TenderLotView.
     */
    case PARTICIPANTS;

    /**
     * Заказчик и компания-исполнитель: процедура завершена (closed/cancelled),
     * посторонним закупка больше не показывается. Исполнитель — поставщик
     * winning-заявки (App\Bid\BidWinnerQuery); пока победителя нет, виден
     * только заказчик.
     */
    case OWNER_AND_WINNER;
}
