<?php

declare(strict_types=1);

namespace App\Auction\Entity\Enum;

/**
 * Круг видимости аукциона в текущем статусе (FR-1.5.14).
 *
 * Видимость аукциона уже, чем видимость его тендера: подготовка торгов
 * (согласование, планирование) — внутренняя кухня заказчика, а всё, что после
 * торгов (пауза, выбор победителя, исполнение, служебные исходы), касается
 * только заказчика и исполнителя лота. Публичен ровно ход торгов.
 * Уровень задаёт AuctionStatusEnum::visibilityLevel().
 */
enum AuctionVisibilityLevelEnum
{
    /** Только сотрудники компании-создателя (заказчика): подготовка торгов. */
    case OWNER_ONLY;

    /** Идут торги: аукцион виден всем, кому виден его тендер. */
    case TENDER_VIEWERS;

    /**
     * Заказчик и компания-исполнитель (победитель лота). Пока победителя нет,
     * уровень равносилен OWNER_ONLY.
     */
    case OWNER_AND_WINNER;
}
