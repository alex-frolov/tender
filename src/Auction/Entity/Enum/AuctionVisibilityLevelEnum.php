<?php

declare(strict_types=1);

namespace App\Auction\Entity\Enum;

/**
 * Круг видимости аукциона в текущем статусе (FR-1.5.14).
 *
 * Видимость аукциона уже, чем видимость его тендера: подготовка торгов
 * (согласование, планирование), пауза, выбор победителя и служебные статусы —
 * внутренняя кухня заказчика, а исполнение после APPROVE касается только
 * заказчика и исполнителя. Публичен ровно ход торгов.
 * Уровень задаёт AuctionStatusEnum::visibilityLevel().
 */
enum AuctionVisibilityLevelEnum
{
    /** Только сотрудники компании-создателя (заказчика). */
    case OWNER_ONLY;

    /** Идут торги: аукцион виден всем, кому виден его тендер. */
    case TENDER_VIEWERS;

    /** Заказчик и компания-исполнитель (победитель лота). */
    case OWNER_AND_WINNER;
}
