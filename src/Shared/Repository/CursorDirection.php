<?php

declare(strict_types=1);

namespace App\Shared\Repository;

/**
 * Направление сортировки списка, к которому применяется keyset-курсор (AR-6).
 *
 * Курсор указывает позицию (created_at, id) последней строки страницы, а
 * «следующая страница» — это строки ЗА ней в порядке самого списка: при ASC
 * — с ключом больше курсора, при DESC — меньше. Направление задаёт вызывающий
 * (KeysetCursor::sliceAfter), потому что порядок задан запросом, а не курсором:
 * для DESC-списка сравнение «больше курсора» отобрало бы первую же строку
 * и страница повторилась бы бесконечно.
 */
enum CursorDirection
{
    /** Список отсортирован по возрастанию (created_at, id) — старые сверху. */
    case ASC;

    /** Список отсортирован по убыванию (created_at, id) — новые сверху. */
    case DESC;
}
